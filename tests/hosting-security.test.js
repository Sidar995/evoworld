test('runtime configuration fails closed for public local-mode binding and unsafe owner settings', () => {
  for (const environment of [
    { HOST: '0.0.0.0', AUTH_MODE: 'local' }, { NODE_ENV: 'production', AUTH_MODE: 'local' }, { RENDER: 'true', AUTH_MODE: 'local' },
    { HOST: '0.0.0.0' }, { NODE_ENV: 'production' },
    { NODE_ENV: 'production', AUTH_MODE: 'owner', OWNER_PASSWORD: PASSWORD, PUBLIC_ORIGIN: 'http://example.invalid' },
    { AUTH_MODE: 'owner', OWNER_PASSWORD: 'too short', PUBLIC_ORIGIN: ORIGIN },
    ...['https://example.invalid/path', 'https://user:password@example.invalid', 'https://example.invalid/?query=1', 'https://example.invalid/#hash'].map(PUBLIC_ORIGIN => ({ AUTH_MODE: 'owner', OWNER_PASSWORD: PASSWORD, PUBLIC_ORIGIN })),
  ]) assert.throws(() => readRuntimeConfig(environment));
  const local = readRuntimeConfig({}); assert.equal(local.host, '127.0.0.1'); assert.equal(local.auth.mode, 'local');
  const hosted = readRuntimeConfig({ NODE_ENV: 'production', PORT: '10000', AUTH_MODE: 'owner', OWNER_PASSWORD: PASSWORD, PUBLIC_ORIGIN: ORIGIN });
  assert.equal(hosted.host, '0.0.0.0'); assert.equal(hosted.port, 10000); assert.equal(hosted.auth.mode, 'owner'); assert.equal(hosted.auth.secure, true);
});
